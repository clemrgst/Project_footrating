"""Inventory of data/raw/ (name, size, record count) written into data/README.md."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

START = "<!-- inventory:start -->"
END = "<!-- inventory:end -->"


def count_player_match(playerank_path: Path) -> int:
    """Number of unique (matchId, playerId) pairs in playerank.json."""
    df = pd.DataFrame(json.loads(playerank_path.read_text(encoding="utf-8")))
    return len(df[["matchId", "playerId"]].drop_duplicates())


def coverage_by_competition(raw_dir: Path) -> list[dict]:
    """playerank.json records and matches per competition, via matchId -> matches_<comp>.json.

    Records whose matchId is in no matches file are counted under "(no match file)".
    """
    competition = {}
    n_matches = {}
    for path in sorted(raw_dir.glob("matches_*.json")):
        name = path.stem.removeprefix("matches_")
        matches = json.loads(path.read_text(encoding="utf-8"))
        n_matches[name] = len(matches)
        competition.update({m["wyId"]: name for m in matches})
    pr = pd.DataFrame(json.loads((raw_dir / "playerank.json").read_text(encoding="utf-8")))
    pr["competition"] = pr["matchId"].map(competition).fillna("(no match file)")
    rows = []
    for name, group in pr.groupby("competition"):
        rows.append(
            {
                "competition": name,
                "records": len(group),
                "matches_covered": group["matchId"].nunique(),
                "matches_in_file": n_matches.get(name),
            }
        )
    return rows


def build_inventory(raw_dir: Path) -> list[dict]:
    """One row per file in raw_dir; records = length of the top-level JSON list."""
    rows = []
    for path in sorted(raw_dir.iterdir()):
        if path.suffix not in {".json", ".zip"}:
            continue
        records = None
        if path.suffix == ".json":
            records = len(json.loads(path.read_text(encoding="utf-8")))
        rows.append({"file": path.name, "bytes": path.stat().st_size, "records": records})
    return rows


def render_inventory(rows: list[dict], n_player_match: int, coverage: list[dict]) -> str:
    lines = [
        START,
        "Generated by `uv run python scripts/download_raw_data.py`; do not edit by hand.",
        "",
        "| File | Size (bytes) | Records |",
        "|---|---:|---:|",
    ]
    for r in rows:
        records = "archive" if r["records"] is None else f"{r['records']:,}"
        lines.append(f"| `{r['file']}` | {r['bytes']:,} | {records} |")
    lines += [
        "",
        f"Player-match rows (unique `matchId`, `playerId` pairs in `playerank.json`): "
        f"**{n_player_match:,}**.",
        "",
        "`playerank.json` coverage by competition (`matchId` matched to `matches_*.json`):",
        "",
        "| Competition | Records | Matches covered | Matches in file |",
        "|---|---:|---:|---:|",
    ]
    for c in coverage:
        in_file = "-" if c["matches_in_file"] is None else f"{c['matches_in_file']:,}"
        lines.append(
            f"| {c['competition']} | {c['records']:,} | {c['matches_covered']:,} | {in_file} |"
        )
    n_players = next(r["records"] for r in rows if r["file"] == "players.json")
    lines += [
        "",
        f"`players.json` lists {n_players:,} players; the data paper (Pappalardo et al., 2019, "
        "Table 1) reports 4,299.",
        END,
    ]
    return "\n".join(lines)


def write_inventory(readme: Path, block: str) -> None:
    """Replace the inventory block in readme, or append it if absent."""
    text = readme.read_text(encoding="utf-8")
    if START in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        text = before + block + after
    else:
        text = text.rstrip("\n") + "\n\n## Inventory\n\n" + block + "\n"
    readme.write_text(text, encoding="utf-8")
